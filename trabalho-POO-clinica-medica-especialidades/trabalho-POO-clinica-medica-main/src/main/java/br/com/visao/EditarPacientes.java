    private void jBpesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBpesquisarActionPerformed
        // TODO add your handling code here:
        String cpf = jTcpfPesquisa.getText().trim();
        if (cpf.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o CPF do paciente.");
            return;
        }

        try {
            // procura o paciente com esse CPF exato
            Paciente encontrado = null;
            for (Paciente p : new ManterPaciente().pesquisar("", cpf, "")) {
                if (p.getCpf().equals(cpf)) {
                    encontrado = p;
                    break;
                }
            }

            if (encontrado == null) {
                JOptionPane.showMessageDialog(this, "Nenhum paciente encontrado com esse CPF.");
                return;
            }

            // guarda o id e mostra os dados para edição
            idPaciente = encontrado.getId();
            jTnome.setText(encontrado.getNome());
            jTcpf.setText(encontrado.getCpf());
            jTemail.setText(encontrado.getEmail());
            jTtelefone.setText(encontrado.getTelefone());
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao pesquisar: " + ex.getMessage());
        }
     
    }//GEN-LAST:event_jBpesquisarActionPerformed

