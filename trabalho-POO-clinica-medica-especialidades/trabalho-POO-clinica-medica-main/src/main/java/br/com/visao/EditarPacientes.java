    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        Paciente p = new Paciente();
        p.setId(idPaciente);
        p.setNome(jTnome.getText().trim());
        p.setCpf(jTcpf.getText().trim());
        p.setEmail(jTemail.getText().trim());
        p.setTelefone(jTtelefone.getText().trim());

        try {
            new ManterPaciente().editarPaciente(p);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao editar: " + ex.getMessage());
        }
    }

