    private void jBcadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBcadastrarActionPerformed
        // monta o objeto com os dados da tela e manda o ManterProfissional gravar
        Profissional p = new Profissional();
        p.setNome(jTnome.getText().trim());
        p.setEmail(jTemail.getText().trim());
        p.setEspecialidade((Especialidade) jCespecialidade.getSelectedItem());
        try {
            if (new ManterProfissional().inserirProfissional(p)) {
                limparCampos();
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao cadastrar: " + ex.getMessage());
        }
    }//GEN-LAST:event_jBcadastrarActionPerformed

