    private void jBpesquisaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBpesquisaActionPerformed
        // TODO add your handling code here:
        DefaultTableModel modelo = (DefaultTableModel) jTable.getModel();
        modelo.setRowCount(0); // limpa a tabela

        try {
            ArrayList<Paciente> lista = new ManterPaciente().pesquisar(
                    jTnome.getText().trim(),
                    jTcpf.getText().trim(),
                    jTemail.getText().trim());

            for (Paciente p : lista) {
                // mesma ordem das colunas: id, nome, cpf, telefone, email
                modelo.addRow(new Object[]{
                    p.getId(), p.getNome(), p.getCpf(), p.getTelefone(), p.getEmail()
                });
            }

            if (lista.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Nenhum paciente encontrado.");
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao pesquisar: " + ex.getMessage());
        }
    }//GEN-LAST:event_jBpesquisaActionPerformed

