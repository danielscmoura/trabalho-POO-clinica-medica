    // Clique em "Excluir": pega o profissional da linha selecionada, pede
    // confirmação e manda o ManterProfissional excluir. Se der certo, a
    // tabela é recarregada sem ele.
    private void jBdeletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBdeletarActionPerformed
        // 1) Exige uma linha selecionada (-1 = nenhuma).
        int linha = jTable.getSelectedRow();
        if (linha < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um profissional na tabela.");
            return;
        }
        // 2) A linha N da tabela corresponde à posição N da "lista"
        //    (convertRowIndexToModel cobre o caso de a tabela ser reordenada).
        Profissional p = lista.get(jTable.convertRowIndexToModel(linha));

        // 3) Pede confirmação mostrando nome e especialidade; qualquer
        //    resposta diferente de "Sim" cancela.
        int resposta = JOptionPane.showConfirmDialog(this,
                "Deseja realmente excluir o profissional " + p.getNome()
                + " (" + p.getEspecialidade().getNome() + ")?",
                "Confirmar exclusão", JOptionPane.YES_NO_OPTION);
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            // 4) deletarProfissional() faz o DELETE, mostra a mensagem
            //    (sucesso ou "possui consultas cadastradas") e devolve true
            //    só quando excluiu de fato.
            if (new ManterProfissional().deletarProfissional(p)) { // exclui pelo id
                pesquisar(false); // tira a linha da tabela
            }
        } catch (Exception ex) {
            // Erro inesperado (ex.: banco fora do ar).
            JOptionPane.showMessageDialog(this, "Erro ao excluir: " + ex.getMessage());
        }
    }//GEN-LAST:event_jBdeletarActionPerformed

