    // Preenche o JComboBox com as especialidades cadastradas no banco.
    // O primeiro item (id = 0) é só um texto de orientação.
    // Nesta tela esse item se chama "Todas": id 0 faz o ManterProfissional
    // não filtrar por especialidade.
    private void carregarEspecialidades() {
        jCespecialidade.removeAllItems();
        jCespecialidade.addItem(new Especialidade(0, "Todas"));
        try {
            // pesquisar("") = sem filtro: traz todas, em ordem alfabética.
            // O combo mostra o nome porque Especialidade sobrescreve toString().
            for (Especialidade e : new ManterEspecialidade().pesquisar("")) {
                jCespecialidade.addItem(e);
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar especialidades: " + ex.getMessage());
        }
    }

    // Aplica os filtros da tela e mostra o resultado na tabela
    // avisarSeVazio = true mostra "Nenhum profissional encontrado" quando a
    // busca não traz nada (usado no botão Pesquisar).
    private void pesquisar(boolean avisarSeVazio) {
        // 1) Apaga as linhas da pesquisa anterior.
        DefaultTableModel modelo = (DefaultTableModel) jTable.getModel();
        modelo.setRowCount(0); // limpa a tabela

        // 2) Descobre o id da especialidade escolhida no filtro.
        Especialidade esp = (Especialidade) jCespecialidade.getSelectedItem();
        int idEspecialidade = (esp == null) ? 0 : esp.getId(); // 0 = todas

        try {
            // 3) Pede ao ManterProfissional a lista filtrada (campos vazios
            //    viram LIKE '%%', que aceita qualquer valor).
            ArrayList<Profissional> lista = new ManterProfissional().pesquisar(
                    jTnome.getText().trim(),
                    jTemail.getText().trim(),
                    idEspecialidade);

            // 4) Cada Profissional vira uma linha da tabela.
            for (Profissional p : lista) {
                // mesma ordem das colunas: ID, Nome, E-mail, Especialidade
                modelo.addRow(new Object[]{
                    p.getId(), p.getNome(), p.getEmail(), p.getEspecialidade().getNome()
                });
            }
            // 5) Atualiza o contador embaixo da tabela.
            jLtotal.setText("Total: " + lista.size() + " profissional(is)");

            if (lista.isEmpty() && avisarSeVazio) {
                JOptionPane.showMessageDialog(this, "Nenhum profissional encontrado.");
            }
        } catch (Exception ex) {
            // Erro de comunicação com o banco.
            JOptionPane.showMessageDialog(this, "Erro ao pesquisar: " + ex.getMessage());
        }
    }

