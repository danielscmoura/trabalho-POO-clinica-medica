    // Clique em "Deletar": acha o paciente pelo CPF, pede confirmação e
    // manda o ManterPaciente excluir pelo id.
    private void jBdeletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBdeletarActionPerformed
        // TODO add your handling code here:
        // 1) Lê o CPF e não deixa seguir com o campo vazio.
        String cpf = jTcpf.getText().trim();
        if (cpf.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Informe o CPF do paciente.");
        return;
        }

        try {
          // Um único objeto ManterPaciente é usado para pesquisar e excluir.
          ManterPaciente manter = new ManterPaciente();

          // 2) pesquisar() usa LIKE (traz CPFs que CONTÊM o texto); o laço
          //    escolhe só o paciente com o CPF exatamente igual.
          Paciente encontrado = null;
          for (Paciente p : manter.pesquisar("", cpf, "")) {
            if (p.getCpf().equals(cpf)) {
                encontrado = p;
                break;
            }
        }

        // 3) Nenhum CPF igual: avisa e para por aqui.
        if (encontrado == null) {
            JOptionPane.showMessageDialog(this, "Nenhum paciente encontrado com esse CPF.");
            return;
        }

        // 4) Pede confirmação mostrando o nome, para evitar excluir a pessoa
        //    errada. Qualquer resposta diferente de "Sim" cancela.
        int resposta = JOptionPane.showConfirmDialog(this,
                "Deseja realmente excluir o paciente " + encontrado.getNome() + "?",
                "Confirmar exclusão", JOptionPane.YES_NO_OPTION);
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        // 5) Executa o DELETE e limpa o campo. A mensagem de sucesso (ou de
        //    "possui consultas cadastradas") é mostrada pelo ManterPaciente.
        manter.deletarPaciente(encontrado); // exclui pelo id que veio da pesquisa
        jTcpf.setText("");
        } catch (Exception ex) {
        // Erro de comunicação com o banco.
        JOptionPane.showMessageDialog(this, "Erro ao excluir: " + ex.getMessage());
      }
    }//GEN-LAST:event_jBdeletarActionPerformed

