    // Clique em "Salvar": monta um Paciente com o id guardado na pesquisa e
    // com o que está nos campos, e pede ao ManterPaciente para gravar.
    // O ManterPaciente valida os campos, impede usar o CPF de OUTRO paciente,
    // faz o UPDATE e mostra a mensagem de sucesso.
    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        // 1) Monta o objeto: o id diz QUAL paciente alterar; os demais campos
        //    são os novos valores (o próprio CPF também pode ser corrigido).
        Paciente p = new Paciente();
        p.setId(idPaciente);
        p.setNome(jTnome.getText().trim());
        p.setCpf(jTcpf.getText().trim());
        p.setEmail(jTemail.getText().trim());
        p.setTelefone(jTtelefone.getText().trim());

        // 2) Chama a classe de lógica, que executa o UPDATE no banco.
        try {
            new ManterPaciente().editarPaciente(p);
        } catch (Exception ex) {
            // 3) Erro inesperado (ex.: banco fora do ar).
            JOptionPane.showMessageDialog(this, "Erro ao editar: " + ex.getMessage());
        }
    }

    // Limpa a tela para começar uma nova edição (método pensado para o
    // botão "Limpar"): zera o id guardado, esvazia todos os campos e devolve
    // o cursor ao campo de pesquisa.
    private void jBlimparActionPerformed(java.awt.event.ActionEvent evt) {
        // Sem id, um "Salvar" acidental não altera nenhum paciente.
        idPaciente = 0;
        jTcpfPesquisa.setText("");
        jTnome.setText("");
        jTcpf.setText("");
        jTemail.setText("");
        jTtelefone.setText("");
        // requestFocus() põe o cursor no campo de pesquisa.
        jTcpfPesquisa.requestFocus();
     
    }//GEN-LAST:event_jBsalvarActionPerformed

