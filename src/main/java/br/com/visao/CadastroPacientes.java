    // Clique em "Cadastrar": junta o que foi digitado em um objeto Paciente
    // e pede para o ManterPaciente gravar no banco. As mensagens de sucesso,
    // de campo obrigatório vazio e de CPF repetido são mostradas pelo próprio
    // ManterPaciente; aqui só tratamos erros inesperados (ex.: banco fora do ar).
    private void jBcadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBcadastrarActionPerformed
        // TODO add your handling code here:
        // 1) Lê os campos (trim() tira espaços sobrando no início e no fim)
        //    e monta o objeto Paciente. O id não é preenchido: o banco gera
        //    sozinho (AUTO_INCREMENT).
        Paciente p = new Paciente();
        p.setNome(jTnome.getText().trim());
        p.setCpf(jTcpf.getText().trim());
        p.setEmail(jTemail.getText().trim());
        p.setTelefone(jTtelefone.getText().trim());
        // 2) Chama a classe de lógica, que valida, confere o CPF e faz o INSERT.
        try {
         new ManterPaciente().inserirPaciente(p);
        } catch (Exception ex) {
         // 3) Se algo der errado na comunicação com o banco, avisa o usuário.
         JOptionPane.showMessageDialog(this, "Erro ao cadastrar: " + ex.getMessage());
       }
        // Obs.: os campos não são limpos depois do cadastro; o texto continua
        // na tela até o usuário apagar ou fechar a janela.
    }//GEN-LAST:event_jBcadastrarActionPerformed

